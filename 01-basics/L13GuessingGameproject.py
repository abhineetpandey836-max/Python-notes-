# Build Guessing Game Project
# We have to learn how to generate random numbers in python. We use import random module to generate random numbers in python. 
# Random module is a built-in module in python which provides functions to generate random numbers. 
# We can use random.randint(a, b) function to generate a random integer between a and b (both inclusive). 
# We can use random.uniform(a, b) function to generate a random float between a and b (both inclusive). We can use random.choice(sequence) function to select a random element from a sequence (like list, tuple, string, etc.). 
# We can use random.shuffle(sequence) function to shuffle the elements of a sequence (like list, tuple, string, etc.) in place. 
# We can use random.sample(population, k) function to select k unique random elements from a population (like list, tuple, string, etc.).
# We can use random.seed(a) function to initialize the random number generator with a seed value. 
# This is useful for reproducibility of results.
import random
random.randint(1, 100)
# it return random integer b/w 1 to 100 randomly in given range a to b (both inclusive).
jackpot=random.randint(1, 100)
guess = int(input("Start Guessing Game"))
counter = 1
while guess != jackpot:
    if guess < jackpot:
        print("Guess higher")
    else:
        print("Guess lower")
    guess = int(input("Enter your guess: "))
    counter += 1
print("Sahi Jawaab")
print("You guessed the number in", counter, "attempts")
# game with while loop is a simple guessing game where the user has to guess a random number generated by the computer. The program provides feedback to the user on whether their guess is too high or too low, and keeps track of the number of attempts made. Once the user guesses the correct number, the program congratulates them and displays the total number of attempts taken to guess the number correctly.